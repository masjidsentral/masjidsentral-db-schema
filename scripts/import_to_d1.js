#!/usr/bin/env node
/**
 * import_to_d1.js — Convert a normalized masjid CSV into SQL and import into Cloudflare D1.
 *
 * Usage:
 *   node import_to_d1.js input.csv output.sql [source_app]
 *
 *   source_app defaults to value in CSV 'source' column, or 'manual' if missing.
 *
 * Setup:
 *   npm install
 *
 * Required CSV columns:
 *   name, lat, lng, geohash, state
 *
 * Optional CSV columns:
 *   type, city, country, address, description,
 *   jumaat_available, telephone, email, google_url, source
 *
 * After running this script:
 *   wrangler d1 execute masjidsentral --remote --file=output.sql
 */

const fs = require('fs')
const path = require('path')
const { parse } = require('csv-parse/sync')

// ─── State ID lookup ───────────────────────────────────────────────────────────
const STATE_MAP = {
  'johor':                          'my-jhr',
  'johor darul ta\'zim':            'my-jhr',
  'johor darul tazim':              'my-jhr',
  'kedah':                          'my-kdh',
  'kelantan':                       'my-ktn',
  'melaka':                         'my-mlk',
  'malacca':                        'my-mlk',
  'negeri sembilan':                'my-nsn',
  'pahang':                         'my-phg',
  'perak':                          'my-prk',
  'perlis':                         'my-pls',
  'pulau pinang':                   'my-png',
  'penang':                         'my-png',
  'sabah':                          'my-sbh',
  'sarawak':                        'my-swk',
  'selangor':                       'my-sgr',
  'selangor darul ehsan':           'my-sgr',
  'terengganu':                     'my-trg',
  'w.p. kuala lumpur':              'my-kul',
  'kuala lumpur':                   'my-kul',
  'kl':                             'my-kul',
  'wp kuala lumpur':                'my-kul',
  'wilayah persekutuan':            'my-kul',
  'wilayah persekutuan kuala lumpur': 'my-kul',
  'federal territory of kuala lumpur': 'my-kul',
  'w.p. labuan':                    'my-lbn',
  'labuan':                         'my-lbn',
  'wp labuan':                      'my-lbn',
  'wilayah persekutuan labuan':     'my-lbn',
  'w.p. putrajaya':                 'my-pjy',
  'putrajaya':                      'my-pjy',
  'wp putrajaya':                   'my-pjy',
  'wilayah persekutuan putrajaya':  'my-pjy',
}

// ─── Country ID lookup ─────────────────────────────────────────────────────────
const COUNTRY_MAP = {
  'my': 'my', 'malaysia': 'my',
  'sg': 'sg', 'singapore': 'sg',
  'bn': 'bn', 'brunei': 'bn',
  'id': 'id', 'indonesia': 'id',
}

// ─── Type ID lookup ────────────────────────────────────────────────────────────
const TYPE_MAP = {
  'masjid':   'masjid',
  'mosque':   'masjid',
  'surau':    'surau',
  'musolla':  'musolla',
  'musalla':  'musolla',
}

// ─── Helpers ───────────────────────────────────────────────────────────────────
const esc = (val) => (val == null || val === '' ? 'NULL' : `'${String(val).replace(/'/g, "''")}'`)
const escNum = (val) => (val == null || val === '' ? 'NULL' : parseFloat(val))
const escInt = (val) => (val == null || val === '' ? '0' : parseInt(val, 10))
const slugify = (s) => s.toLowerCase().trim().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, '')

function toStateId(countryId, stateName) {
  return `${countryId}-${slugify(stateName)}`
}

function toCityId(stateId, cityName) {
  return `${stateId}-${slugify(cityName)}`
}

// ─── Main ──────────────────────────────────────────────────────────────────────
const [, , inputFile, outputFile, sourceAppArg] = process.argv

if (!inputFile || !outputFile) {
  console.error('Usage: node import_to_d1.js input.csv output.sql [source_app]')
  process.exit(1)
}

const raw = fs.readFileSync(path.resolve(inputFile), 'utf8')
const records = parse(raw, { columns: true, skip_empty_lines: true })

if (!records.length) {
  console.error('Error: CSV is empty.')
  process.exit(1)
}

const requiredCols = ['name', 'lat', 'lng', 'geohash', 'state']
const missing = requiredCols.filter((col) => !(col in records[0]))
if (missing.length) {
  console.error(`Error: CSV is missing required columns: ${missing.join(', ')}`)
  process.exit(1)
}

const lines = []
const errors = []
const stateInserts = new Map() // stateId → INSERT statement (non-Malaysian states)
const cityInserts = new Map()  // cityId  → INSERT statement

lines.push('-- Generated by import_to_d1.js')
lines.push(`-- Source: ${inputFile}`)
lines.push(`-- Records: ${records.length}`)
lines.push(`-- Date: ${new Date().toISOString()}`)
lines.push('')

const masjidLines = []

for (let i = 0; i < records.length; i++) {
  const row = records[i]
  const rowNum = i + 2 // 1-based + header row

  // ── Resolve country ──
  const countryId = COUNTRY_MAP[(row.country || 'MY').toLowerCase().trim()]
  if (!countryId) {
    errors.push(`Row ${rowNum}: unsupported country '${row.country}' — skipped`)
    continue
  }

  // ── Resolve state ──
  const stateRaw = (row.state || '').toLowerCase().trim()
  let stateId = STATE_MAP[stateRaw]
  if (!stateId) {
    if (countryId === 'my') {
      errors.push(`Row ${rowNum}: unknown Malaysian state '${row.state}' — skipped`)
      continue
    }
    // Non-Malaysian: generate state ID and schedule INSERT OR IGNORE
    const stateName = (row.state && row.state.trim()) ? row.state.trim() : row.country.trim()
    stateId = toStateId(countryId, stateName)
    if (!stateInserts.has(stateId)) {
      stateInserts.set(stateId, `INSERT OR IGNORE INTO states (id, name, country_id) VALUES ('${stateId}', ${esc(stateName)}, '${countryId}');`)
    }
  }

  // ── Resolve type (default: masjid) ──
  const typeRaw = (row.type || 'masjid').toLowerCase().trim()
  const typeId = TYPE_MAP[typeRaw] || 'masjid'

  // ── Resolve city ──
  let cityId = 'NULL'
  if (row.city && row.city.trim()) {
    const id = toCityId(stateId, row.city)
    cityId = `'${id}'`
    if (!cityInserts.has(id)) {
      cityInserts.set(id, `INSERT OR IGNORE INTO cities (id, name, state_id) VALUES ('${id}', ${esc(row.city.trim())}, '${stateId}');`)
    }
  }

  // ── Resolve source ──
  const source = sourceAppArg || row.source || 'manual'

  masjidLines.push(
    `INSERT INTO masjids (name, type_id, lat, lng, geohash, city_id, state_id, country_id, address, description, jumaat_available, telephone, email, google_url, source) VALUES (` +
    `${esc(row.name)}, ` +
    `'${typeId}', ` +
    `${escNum(row.lat)}, ` +
    `${escNum(row.lng)}, ` +
    `${esc(row.geohash)}, ` +
    `${cityId}, ` +
    `'${stateId}', ` +
    `'${countryId}', ` +
    `${esc(row.address)}, ` +
    `${esc(row.description)}, ` +
    `${escInt(row.jumaat_available)}, ` +
    `${esc(row.telephone)}, ` +
    `${esc(row.email)}, ` +
    `${esc(row.google_url)}, ` +
    `${esc(source)}` +
    `);`
  )
}

// States before cities (foreign key dependency)
if (stateInserts.size) {
  lines.push('-- States (non-Malaysian)')
  lines.push(...stateInserts.values())
  lines.push('')
}

if (cityInserts.size) {
  lines.push('-- Cities')
  lines.push(...cityInserts.values())
  lines.push('')
}

lines.push('-- Masjids')
lines.push(...masjidLines)

fs.writeFileSync(path.resolve(outputFile), lines.join('\n'))

console.log(`\nSQL file written: ${outputFile}`)
console.log(`  ${masjidLines.length} masjid records`)
if (stateInserts.size) console.log(`  ${stateInserts.size} new states (non-Malaysian)`)
console.log(`  ${cityInserts.size} new cities`)
if (errors.length) {
  console.log(`\n⚠️  ${errors.length} rows skipped:`)
  errors.forEach((e) => console.log(`   ${e}`))
}
console.log(`\nNext step — import to D1:`)
console.log(`  wrangler d1 execute masjidsentral --remote --file=${outputFile}`)
